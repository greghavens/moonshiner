PRAGMA foreign_keys = ON;

CREATE TABLE reservations (
    stable_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    location TEXT NOT NULL,
    status TEXT NOT NULL,
    event_date TEXT NOT NULL,
    starts_at TEXT NOT NULL,
    ends_at TEXT NOT NULL,
    space TEXT NOT NULL,
    guest_count INTEGER NOT NULL,
    organizer TEXT NOT NULL,
    internal_note TEXT NOT NULL
);

CREATE TABLE saved_profiles (
    profile_name TEXT PRIMARY KEY,
    preference TEXT NOT NULL
);

CREATE TABLE availability (
    reservation_id TEXT NOT NULL,
    service_date TEXT NOT NULL,
    available INTEGER NOT NULL CHECK (available IN (0, 1)),
    PRIMARY KEY (reservation_id, service_date),
    FOREIGN KEY (reservation_id) REFERENCES reservations(stable_id)
);

CREATE TABLE notifications (
    sequence INTEGER PRIMARY KEY AUTOINCREMENT,
    reservation_id TEXT NOT NULL,
    message TEXT NOT NULL,
    FOREIGN KEY (reservation_id) REFERENCES reservations(stable_id)
);

CREATE TABLE execution_journal (
    sequence INTEGER PRIMARY KEY AUTOINCREMENT,
    operation TEXT NOT NULL,
    arguments_json TEXT NOT NULL,
    started_ns INTEGER NOT NULL,
    pid INTEGER NOT NULL,
    parent_pid INTEGER NOT NULL,
    harness_action INTEGER NOT NULL,
    finished_ns INTEGER,
    result_count INTEGER,
    sole_id TEXT,
    result_digest TEXT,
    violation INTEGER NOT NULL DEFAULT 0,
    error TEXT
);

CREATE TABLE runtime_metadata (
    singleton INTEGER PRIMARY KEY CHECK (singleton = 1),
    reference_mode INTEGER NOT NULL CHECK (reference_mode IN (0, 1))
);

