def check(label, condition, detail=""):
    checks[0] += 1
    if condition:
        print("  PASS  %s" % label)
    else:
        print("  FAIL  %s" % label)
        if detail:
            for line in str(detail).splitlines():
                print("        %s" % line)
        failures.append(label)


def check_equal(label, actual, expected):
    ok = actual == expected
    detail = ""
    if not ok:
        detail = "expected: %s\nactual:   %s" % (
            json.dumps(expected, sort_keys=True, default=str),
            json.dumps(actual, sort_keys=True, default=str),
        )
    check(label, ok, detail)


def as_list(value):
    """PowerShell's ConvertTo-Json collapses single-element arrays to objects."""
    if value is None:
        return []
    if isinstance(value, list):
        return value
    return [value]


# ---------------------------------------------------------------------------
# Fixture lifecycle
# ---------------------------------------------------------------------------


class Fixture:
    def __init__(self, log_path, fail_tier=None, fail_operation=None, fail_status=400,
                 fail_message=FAIL_MESSAGE):
        self.log_path = log_path
        cmd = [sys.executable, MOCK, "--contract", CONTRACT, "--log", log_path, "--port", "0"]
        if fail_tier:
            cmd += ["--fail-tier", fail_tier]
        if fail_operation:
            cmd += ["--fail-operation", fail_operation]
        if fail_tier or fail_operation:
            cmd += ["--fail-status", str(fail_status), "--fail-message", fail_message]
        self.proc = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        line = self.proc.stdout.readline()
        m = re.match(r"PORT (\d+)", line or "")
        if not m:
            self.proc.kill()
            raise RuntimeError("fixture did not start: %r %s" % (line, self.proc.stderr.read()))
        self.port = int(m.group(1))
        self._await_ready()

    def _await_ready(self):
        deadline = time.time() + 10
        url = "http://127.0.0.1:%d%s/__ready" % (self.port, BASE)
        while time.time() < deadline:
            try:
                urllib.request.urlopen(url, timeout=1)
                return
            except urllib.error.HTTPError:
                return  # a 404 from the contract router means it is serving
            except OSError:
                time.sleep(0.05)
        raise RuntimeError("fixture never became ready")

    def requests(self):
        entries = []
        with open(self.log_path, encoding="utf-8") as fh:
            for line in fh:
                if line.strip():
                    entries.append(json.loads(line))
        # drop the readiness probe
        return [e for e in entries if not e["path"].endswith("/__ready")]

    def stop(self):
        self.proc.terminate()
        try:
            self.proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            self.proc.kill()


def run_scenario(scenario, fail_tier=None, fail_operation=None, fail_status=400,
                 fail_message=FAIL_MESSAGE):
    with tempfile.TemporaryDirectory(prefix="vcfon-%s-" % scenario) as workdir:
        log_path = os.path.join(workdir, "requests.jsonl")
        out_path = os.path.join(workdir, "result.json")
        fixture = Fixture(log_path, fail_tier, fail_operation, fail_status, fail_message)
        try:
            proc = subprocess.run(
                [
                    "pwsh", "-NoProfile", "-NonInteractive", "-File", DRIVER,
                    "-ModulePath", MANIFEST,
                    "-Scenario", scenario,
                    "-ServerHost", "127.0.0.1",
                    "-Port", str(fixture.port),
                    "-OutFile", out_path,
                ],
                capture_output=True, text=True, timeout=300,
            )
            requests = fixture.requests()
        finally:
            fixture.stop()

        report = None
        if os.path.exists(out_path):
            with open(out_path, encoding="utf-8") as fh:
                report = json.load(fh)
        return proc, requests, report


def summarise(requests):
    return [(r["method"], r["path"]) for r in requests]


# ---------------------------------------------------------------------------
# Static checks on the module itself
# ---------------------------------------------------------------------------


def check_module_wiring():
    print("\n[1] module packaging")

    probe = (
        "$ErrorActionPreference='Stop'; $WarningPreference='SilentlyContinue';"
        "Import-Module '%s' -Force -ErrorAction Stop;"
        "[pscustomobject]@{"
        " exported = @((Get-Command -Module VCFOpsNetworks).Name | Sort-Object) }"
        " | ConvertTo-Json -Depth 6"
    ) % MANIFEST

    proc = subprocess.run(
        ["pwsh", "-NoProfile", "-NonInteractive", "-Command", probe],
        capture_output=True, text=True, timeout=300,
    )
    try:
        info = json.loads(proc.stdout)
    except ValueError:
        check("module imports cleanly", False, proc.stdout + "\n" + proc.stderr)
        return

    vendored = []
    for dirpath, _dirnames, filenames in os.walk(MODULE_DIR):
        for name in filenames:
            if name.lower().startswith("vmware.sdk.vcf") or name.lower().endswith(".dll"):
                vendored.append(os.path.join(dirpath, name))
    check("no DLLs or copied SDK files under src/VCFOpsNetworks", not vendored, "\n".join(vendored))

    check_equal(
        "module exports exactly the three contracted functions",
        as_list(info.get("exported")),
        ["Connect-VCFOpsNetworksServer", "Disconnect-VCFOpsNetworksServer", "New-VCFOpsNetworksApplication"],
    )


