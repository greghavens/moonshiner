def check_application_failure():
    print("\n[4] application rejection is reported and no listing is attempted")
    proc, requests, report = run_scenario(
        "application-failure",
        fail_operation="addApplication",
        fail_status=409,
        fail_message=APP_FAIL_MESSAGE,
    )

    if report is None:
        check("driver produced a report", False, proc.stdout + "\n" + proc.stderr)
        return
    check("Connect-VCFOpsNetworksServer succeeded", report.get("connect_error") is None, report.get("connect_error"))
    check_equal(
        "only addApplication is attempted",
        summarise(requests),
        [("POST", BASE + "/groups/applications")],
    )
    check(
        "the application rejection is returned rather than thrown",
        report.get("rollout_error") is None,
        report.get("rollout_error"),
    )
    rollout = report.get("rollout")
    if not isinstance(rollout, dict):
        check("New-VCFOpsNetworksApplication returned a result object", False, rollout)
        return
    check_equal("failed application rollout Status", rollout.get("Status"), "Failed")
    check_equal("failed application rollout ApplicationName", rollout.get("ApplicationName"), "Payments-Prod")
    check_equal("failed application rollout ApplicationEntityId", rollout.get("ApplicationEntityId"), None)
    check_equal("no tiers can be confirmed when application creation fails", as_list(rollout.get("CreatedTiers")), [])
    check_equal(
        "only the failed addApplication step is reported",
        [
            {
                "Index": s.get("Index"), "Operation": s.get("Operation"),
                "Target": s.get("Target"), "Status": s.get("Status"),
                "EntityId": s.get("EntityId"),
            }
            for s in as_list(rollout.get("Steps"))
        ],
        [
            {
                "Index": 1, "Operation": "addApplication", "Target": "Payments-Prod",
                "Status": "Failed", "EntityId": None,
            }
        ],
    )
    failed = rollout.get("FailedStep")
    check_equal("failed application operation", (failed or {}).get("Operation"), "addApplication")
    check_equal("failed application target", (failed or {}).get("Target"), "Payments-Prod")
    check_equal("failed application status code", (failed or {}).get("StatusCode"), 409)
    check_equal("failed application appliance message", (failed or {}).get("Message"), APP_FAIL_MESSAGE)


