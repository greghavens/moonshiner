def check_rollout_failure():
    print("\n[2] native session auth, three-tier rollout, third tier rejected")
    proc, requests, report = run_scenario("rollout-failure", fail_tier="db")

    if report is None:
        check("driver produced a report", False, proc.stdout + "\n" + proc.stderr)
        return
    check("module imported without error", report.get("import_error") is None, report.get("import_error"))
    check("Connect-VCFOpsNetworksServer succeeded", report.get("connect_error") is None, report.get("connect_error"))

    # -- wire shape ---------------------------------------------------------
    expected_calls = [
        ("POST", BASE + "/auth/token"),
        ("POST", BASE + "/groups/applications"),
        ("POST", BASE + "/groups/applications/%s/tiers" % APP_ID),
        ("POST", BASE + "/groups/applications/%s/tiers" % APP_ID),
        ("POST", BASE + "/groups/applications/%s/tiers" % APP_ID),
        ("GET", BASE + "/groups/applications/%s/tiers" % APP_ID),
        ("DELETE", BASE + "/auth/token"),
    ]
    check_equal("exact sequence of API calls", summarise(requests), expected_calls)
    if len(requests) != len(expected_calls):
        return

    auth, app, web, tier_app, db, listing, logout = requests

    check_equal(
        "operationId 'create' body omits the unset optional 'domain'",
        auth["body_json"],
        {"username": USERNAME, "password": PASSWORD},
    )
    check(
        "operationId 'create' is sent unauthenticated",
        "authorization" not in auth["headers"],
        auth["headers"],
    )
    check_equal(
        "operationId 'create' declares Content-Type application/json",
        (auth["headers"].get("content-type") or "").split(";")[0].strip(),
        "application/json",
    )

    check_equal(
        "operationId 'addApplication' body carries only 'name'",
        app["body_json"],
        {"name": "Payments-Prod"},
    )
    check_equal(
        "session token is presented as the ApiKeyAuth scheme",
        app["headers"].get("authorization"),
        TOKEN,
    )

    check_equal(
        "tier 'web' sends only a SearchMembershipCriteria; member_list and source_group_entity_id omitted",
        web["body_json"],
        {
            "name": "web",
            "group_membership_criteria": [
                {
                    "membership_type": "SearchMembershipCriteria",
                    "search_membership_criteria": {
                        "entity_type": "VirtualMachine",
                        "filter": "security_groups.entity_id = '18230:82:604573173'",
                    },
                }
            ],
        },
    )
    check_equal(
        "tier 'app' sends only an IPAddressMembershipCriteria",
        tier_app["body_json"],
        {
            "name": "app",
            "group_membership_criteria": [
                {
                    "membership_type": "IPAddressMembershipCriteria",
                    "ip_address_membership_criteria": {
                        "ip_addresses": ["10.10.20.0/24", "10.10.21.5-10.10.21.40"]
                    },
                }
            ],
        },
    )
    check_equal(
        "tier 'db' sends source_group_entity_id because it was set",
        db["body_json"],
        {
            "name": "db",
            "group_membership_criteria": [
                {
                    "membership_type": "SearchMembershipCriteria",
                    "search_membership_criteria": {
                        "entity_type": "VirtualMachine",
                        "filter": "vm_tag = 'payments-db'",
                    },
                }
            ],
            "source_group_entity_id": ["18230:566:264351372"],
        },
    )
    check("operationId 'listApplicationTiers' sends no body", listing["body_raw"] == "", listing["body_raw"])
    check("operationId 'delete' sends no body", logout["body_raw"] == "", logout["body_raw"])
    check_equal("operationId 'delete' presents the session token", logout["headers"].get("authorization"), TOKEN)

    # -- reporting accuracy -------------------------------------------------
    check(
        "an API rejection is reported, not thrown as a terminating error",
        report.get("rollout_error") is None,
        report.get("rollout_error"),
    )
    rollout = report.get("rollout")
    if not isinstance(rollout, dict):
        check("New-VCFOpsNetworksApplication returned a result object", False, rollout)
        return

    check_equal("rollout Status", rollout.get("Status"), "Failed")
    check_equal("rollout ApplicationName", rollout.get("ApplicationName"), "Payments-Prod")
    check_equal("rollout ApplicationEntityId", rollout.get("ApplicationEntityId"), APP_ID)

    steps = [
        {
            "Index": s.get("Index"),
            "Operation": s.get("Operation"),
            "Target": s.get("Target"),
            "Status": s.get("Status"),
            "EntityId": s.get("EntityId"),
        }
        for s in as_list(rollout.get("Steps"))
    ]
    check_equal(
        "every attempted step is reported with its true outcome, and no step after the failure",
        steps,
        [
            {
                "Index": 1, "Operation": "addApplication", "Target": "Payments-Prod",
                "Status": "Succeeded", "EntityId": APP_ID,
            },
            {
                "Index": 2, "Operation": "addTier", "Target": "web",
                "Status": "Succeeded", "EntityId": "18230:562:200000001",
            },
            {
                "Index": 3, "Operation": "addTier", "Target": "app",
                "Status": "Succeeded", "EntityId": "18230:562:200000002",
            },
            {
                "Index": 4, "Operation": "addTier", "Target": "db",
                "Status": "Failed", "EntityId": None,
            },
        ],
    )

    failed = rollout.get("FailedStep")
    if isinstance(failed, dict):
        check_equal("FailedStep operation", failed.get("Operation"), "addTier")
        check_equal("FailedStep target", failed.get("Target"), "db")
        check_equal("FailedStep status code", failed.get("StatusCode"), 400)
        check(
            "FailedStep carries the appliance's own error message",
            FAIL_MESSAGE in str(failed.get("Message")),
            failed.get("Message"),
        )
    else:
        check("FailedStep describes the rejected step", False, failed)

    created = [
        {"Name": t.get("Name"), "EntityId": t.get("EntityId")}
        for t in as_list(rollout.get("CreatedTiers"))
    ]
    check_equal(
        "CreatedTiers reflects the tiers confirmed to exist server-side",
        created,
        [
            {"Name": "web", "EntityId": "18230:562:200000001"},
            {"Name": "app", "EntityId": "18230:562:200000002"},
        ],
    )
    check(
        "the partially applied change was left in place, not rolled back",
        not any(r["method"] == "DELETE" and "/groups/" in r["path"] for r in requests),
        summarise(requests),
    )
    check("Disconnect-VCFOpsNetworksServer succeeded", report.get("disconnect_error") is None, report.get("disconnect_error"))


